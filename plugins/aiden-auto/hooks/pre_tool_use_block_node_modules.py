#!/usr/bin/env python
"""Block node_modules / build artifacts under .claude/skills/

Why: 2026-05-08 critic cleanup found a single skill's node_modules bloating
.claude/ to 158 MB (88% of total). Skills are SKILL.md based; JS deps belong
in a standalone project, not under .claude/skills/.

Triggered as PreToolUse hook for Bash | Write | Edit. Blocks:
  - Write/Edit to any path matching .claude/skills/*/node_modules/
  - Bash 'npm/pnpm/yarn install' executed inside .claude/skills/

Exit code 2 + stderr message blocks the tool call (Claude Code spec).
"""
import json
import re
import sys

PATH_BLOCK = re.compile(
    r"[\\/]\.claude[\\/]skills[\\/][^\\/]+[\\/]node_modules",
    re.IGNORECASE,
)
BASH_INSTALL = re.compile(r"\b(npm|pnpm|yarn)\s+(install|i|add|ci)\b")
SKILLS_CWD = re.compile(r"[\\/]\.claude[\\/]skills[\\/]", re.IGNORECASE)


def block(reason: str) -> None:
    sys.stderr.write(
        f"[block_node_modules] BLOCKED: {reason}\n"
        "Reason: 2026-05-08 critic cleanup removed 158 MB node_modules from a skill.\n"
        "Fix: if this skill needs JS dependencies, extract it to a standalone repo.\n"
    )
    sys.exit(2)


def main() -> None:
    try:
        data = json.load(sys.stdin)
    except Exception:
        sys.exit(0)

    tool = data.get("tool_name", "")
    tool_input = data.get("tool_input") or {}
    cwd = data.get("cwd", "") or ""

    if tool in ("Write", "Edit"):
        path = tool_input.get("file_path", "") or ""
        if PATH_BLOCK.search(path):
            block(f"node_modules under .claude/skills/ — path: {path}")

    elif tool == "Bash":
        cmd = tool_input.get("command", "") or ""
        if SKILLS_CWD.search(cwd) and BASH_INSTALL.search(cmd):
            block(f"npm/pnpm/yarn install inside .claude/skills/ — cwd: {cwd}")

    sys.exit(0)


if __name__ == "__main__":
    main()
